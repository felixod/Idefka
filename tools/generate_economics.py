# -*- coding: utf-8 -*-
"""Экономика и финмодель (каркас): docs-org/Экономика.md

Раздел 1 — статьи затрат (каркас реальной финмодели: план/факт заполнять руками),
раздел 2 — МЕТОДИКА Ф1-Ф10 (расчётные формулы из org; это НЕ факт),
раздел 3 — стоимость по отделам, раздел 4 — управленческий цикл.
Деньги НЕ входят в Положения и ДИ — только сюда, в ABC-диалог и CSV-смету.
"""
import io
import json

ORG = "tools/org_structure.json"
OUT = "docs-org/Экономика.md"

def fmt(v):
    return f"{v:,.0f}".replace(",", "\u202f")

def main():
    org = json.load(io.open(ORG, encoding="utf-8"))
    p = org["params"]
    M, S = p["months"], 1 + p["social_rate"]
    deps = org["departments"]
    roles = [(d, r) for d in deps for r in d["roles"]]
    fot = lambda r: (r["salary_min"] + r["salary_max"]) / 2 * r["fte"] * M * S
    svc = sum(fot(r) for d, r in roles if d.get("kind") == "service")
    total = sum(fot(r) for d, r in roles)
    oh = svc * p["overhead_rate"]
    cost = svc + oh
    mg = cost * p["margin_rate"]
    price = cost + mg
    users = p["sites"] * p["users_per_site"]
    tix_y = p["tickets_per_month"] * M

    L = [
        f"# Экономика и финмодель (каркас) — {org['company']}", "",
        "Деньги живут ТОЛЬКО здесь, в ABC-диалоге и CSV-смете. Положения и ДИ — без сумм.",
        "", "## 1. Статьи затрат (заполнить фактами — план/факт)", "",
        "| Статья | Источник данных | Период | План | Факт |",
        "|---|---|---|---|---|",
        "| ФОТ (вкл. взносы) | org (Ф1–Ф3) | мес | авто | — |",
        "| ПО и лицензии | закупки (A53) | год | — | — |",
        "| Оборудование и амортизация | ITAM (A41) | год | — | — |",
        "| Подрядчики и вендоры | договоры (A53) | мес | — | — |",
        "| ЦОД и инфраструктура | финучёт | мес | — | — |",
        "| Прочие накладные | финучёт | мес | — | — |",
        "",
        "Распределение на сервисы — по драйверам: пользователи, объекты, обращения (Ф7–Ф9).",
        "Формулы ниже — МЕТОДИКА (расчёт по вилкам), а не факт: факт начинается с таблицы выше.",
        "", "## 2. Методика Ф1–Ф10 (расчёт по вилкам org)", "",
        "| # | Формула | Расшифровка |",
        "|---|---|---|",
        "| Ф1 | `ФОТ_роли = (оклад_мин + оклад_макс)/2 × FTE × мес × (1+взносы)` | вилка × штат × период |",
        "| Ф2 | `ФОТ_отдела = Σ ФОТ_ролей` | подразделение |",
        "| Ф3 | `ФОТ_компании = Σ ФОТ_отделов` | весь персонал |",
        "| Ф4 | `Стоимость_работы = Σ (ФОТ_роли / работ_роли)` | распределение (методическое допущение) |",
        "| Ф5 | `Себестоимость = Σ ФОТ(service) × (1+накладные)` | обслуживание |",
        "| Ф6 | `Цена_договора = Себестоимость × (1+маржа)` | для Компании |",
        "| Ф7–Ф9 | тарифы за объект / пользователя / обращение | приложение к договору |",
        "| Ф10 | `Цена_обращения_L1 = ФОТ(L1)/обращения` | первая линия |",
        "", "### Подстановка (текущие параметры org)", "",
        f"- Взносы +{p['social_rate']*100:.1f}%, накладные +{p['overhead_rate']*100:.0f}%, маржа +{p['margin_rate']*100:.0f}%",
        f"- Объектов {p['sites']}, пользователей {users}, обращений {fmt(p['tickets_per_month'])}/мес",
        "",
        "| Величина | Расчёт | Значение |",
        "|---|---|---|",
        f"| ФОТ компании (Ф3) | {fmt(total)} ₽/год | {fmt(total/M)} ₽/мес |",
        f"| ФОТ обслуживания (Ф5) | service-отделы | {fmt(svc)} ₽/год |",
        f"| Накладные (Ф5) | +{p['overhead_rate']*100:.0f}% | {fmt(oh)} ₽/год |",
        f"| Себестоимость (Ф5) | | **{fmt(cost)} ₽/год** |",
        f"| Маржа (Ф6) | +{p['margin_rate']*100:.0f}% | {fmt(mg)} ₽/год |",
        f"| **Цена договора (Ф6)** | | **{fmt(price)} ₽/год = {fmt(price/M)} ₽/мес** |",
        f"| Тариф за объект (Ф7) | | {fmt(price/p['sites']/M)} ₽/мес |",
        f"| Тариф за пользователя (Ф8) | | {fmt(price/users/M)} ₽/мес |",
        f"| Тариф за обращение (Ф9) | | {fmt(price/tix_y)} ₽ |",
    ]

    L += ["", "## 3. Стоимость по отделам (Ф1+Ф2)", "",
          "| Отдел | Тип | Штат | ФОТ/год | В себестоимость? |",
          "|---|---|---|---|---|"]
    for d in deps:
        f = sum(fot(r) for r in d["roles"])
        in_svc = "да (Ф5)" if d.get("kind") == "service" else "нет (накладные/проекты)"
        L.append(f"| {d['name']} | {d.get('kind', 'internal')} | "
                 f"{sum(r['fte'] for r in d['roles'])} | {fmt(f)} | {in_svc} |")

    L += ["", "## 4. Управленческий цикл", "",
          "1. Факт затрат — в таблицу раздела 1 (план/факт по статьям).",
          "2. Изменили оклады/FTE в org → пересчитались Ф1–Ф9 и ABC (кнопка «Синхронизировать»).",
          "3. Квартал: факт vs план → отклонения → SLA-отчёт предприятиям (A54).",
          "4. Торг по договору: маржа/объёмы → тарифы Ф7–Ф9 пересчитываются.",
          "5. Норматив: тариф пользователя держать в рынке.", ""]

    io.open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"OK -> {OUT}")

if __name__ == "__main__":
    main()
